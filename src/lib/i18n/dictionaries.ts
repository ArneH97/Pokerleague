/**
 * Vertalingen.
 *
 * Bewust één bestand met platte sleutels in plaats van een vertaalbibliotheek.
 * Zolang het om een paar honderd zinnen gaat is dit sneller, volledig
 * typeveilig, en zie je in één oogopslag welke taal iets mist — de compiler
 * klaagt namelijk als een taal een sleutel niet heeft.
 *
 * Nederlands is de bron. Wie een sleutel toevoegt aan `nl` móet hem ook in
 * `fr` en `en` zetten, anders faalt de typecheck.
 */

export const LOCALES = ['nl', 'fr', 'en'] as const
export type Locale = (typeof LOCALES)[number]

export const LOCALE_NAMES: Record<Locale, string> = {
  nl: 'Nederlands',
  fr: 'Français',
  en: 'English',
}

export function isLocale(v: string | null | undefined): v is Locale {
  return typeof v === 'string' && (LOCALES as readonly string[]).includes(v)
}

